"""Forge provider dispatcher used by every pipeline stage."""

from __future__ import annotations

from collections.abc import Iterable

from orch.config.logger import get_logger
from orch.constants.standards import BOT_MARKER
from orch.schemas.config.types import Config
from orch.schemas.github.types import (
    Comment,
    Issue,
    PullRequestRef,
    PullRequestStatus,
)
from orch.services import forgejo, github

log = get_logger(component="forge")


def _is_forgejo(config: Config) -> bool:
    return config.repo.forge == "forgejo"


def resolve_token(config: Config) -> str:
    """Resolve the token for the configured forge."""
    if _is_forgejo(config):
        return forgejo.resolve_token(config.forgejo_token)
    return github.resolve_token(config.repo.owner, config.gh_token)


def ensure_user(config: Config, token: str) -> None:
    """Verify that the token belongs to the configured repository owner."""
    if _is_forgejo(config):
        forgejo.ensure_user(config.repo.url, token, config.repo.owner)
    else:
        github.ensure_user(token, config.repo.owner)


def check_repo(config: Config, token: str) -> None:
    """Verify that the token can read the configured repository."""
    if _is_forgejo(config):
        forgejo.check_repo(config.repo.url, config.repo.full_name, token)
    else:
        github.check_repo(config.repo.full_name, token)


def ensure_labels(
    config: Config,
    token: str,
    labels: list[tuple[str, str, str]],
) -> None:
    """Create or update the labels used by the pipeline."""
    if _is_forgejo(config):
        forgejo.ensure_labels(config.repo.url, config.repo.full_name, token, labels)
    else:
        github.ensure_labels(config.repo.full_name, token, labels)


def list_ready_issues(config: Config, label: str, token: str) -> list[Issue]:
    """Return open issues carrying the ready label, oldest first."""
    if _is_forgejo(config):
        return forgejo.list_ready_issues(
            config.repo.url,
            config.repo.full_name,
            label,
            token,
        )
    return github.list_ready_issues(config.repo.full_name, label, token)


def get_issue(config: Config, number: int, token: str) -> Issue:
    """Fetch one issue by number."""
    if _is_forgejo(config):
        return forgejo.get_issue(config.repo.url, config.repo.full_name, number, token)
    return github.get_issue(config.repo.full_name, number, token)


def issue_is_open(config: Config, number: int, token: str) -> bool:
    """Return whether an issue is still open."""
    if _is_forgejo(config):
        return forgejo.issue_is_open(
            config.repo.url,
            config.repo.full_name,
            number,
            token,
        )
    return github.issue_is_open(config.repo.full_name, number, token)


def edit_labels(
    config: Config,
    number: int,
    token: str,
    *,
    add: tuple[str, ...] = (),
    remove: tuple[str, ...] = (),
) -> None:
    """Add and remove labels on an issue."""
    if _is_forgejo(config):
        forgejo.edit_labels(
            config.repo.url,
            config.repo.full_name,
            number,
            token,
            add=add,
            remove=remove,
        )
    else:
        github.edit_labels(
            config.repo.full_name,
            number,
            token,
            add=add,
            remove=remove,
        )


def comment_issue(config: Config, number: int, token: str, body: str) -> None:
    """Post a comment on an issue."""
    if _is_forgejo(config):
        forgejo.comment_issue(
            config.repo.url,
            config.repo.full_name,
            number,
            token,
            body,
        )
    else:
        github.comment_issue(config.repo.full_name, number, token, body)


def mark_bot_body(body: str) -> str:
    """Append the machine-readable orch marker to a comment body."""
    return f"{body}\n\n{BOT_MARKER}"


def comment_bot_issue(config: Config, number: int, token: str, body: str) -> None:
    """Post a comment marked as generated by orch."""
    comment_issue(config, number, token, mark_bot_body(body))


def list_issue_comments(
    config: Config,
    number: int,
    token: str,
    *,
    since: str | None = None,
) -> list[Comment]:
    """Return issue comments, optionally updated after an ISO timestamp."""
    if _is_forgejo(config):
        return forgejo.list_issue_comments(
            config.repo.url,
            config.repo.full_name,
            number,
            token,
            since=since,
        )
    return github.list_issue_comments(
        config.repo.full_name,
        number,
        token,
        since=since,
    )


def find_open_pr(config: Config, head: str, token: str) -> str | None:
    """Return the URL of an open pull request for the branch, if any."""
    if _is_forgejo(config):
        return forgejo.find_open_pr(
            config.repo.url,
            config.repo.full_name,
            head,
            token,
        )
    return github.find_open_pr(config.repo.full_name, head, token)


def find_open_pr_for_issue(
    config: Config,
    issue_number: int,
    token: str,
    *,
    preferred_head: str | None = None,
) -> PullRequestRef | None:
    """Return the open pull request that belongs to an issue."""
    if _is_forgejo(config):
        return forgejo.find_open_pr_for_issue(
            config.repo.url,
            config.repo.full_name,
            issue_number,
            token,
            preferred_head=preferred_head,
        )
    return github.find_open_pr_for_issue(
        config.repo.full_name,
        issue_number,
        token,
        preferred_head=preferred_head,
    )


def open_pr_issue_numbers(
    config: Config,
    issue_numbers: Iterable[int],
    token: str,
) -> set[int]:
    """Return which of the given issues have an open pull request."""
    if _is_forgejo(config):
        return forgejo.open_pr_issue_numbers(
            config.repo.url,
            config.repo.full_name,
            issue_numbers,
            token,
        )
    return github.open_pr_issue_numbers(
        config.repo.full_name,
        issue_numbers,
        token,
    )


def create_pr(
    config: Config,
    token: str,
    *,
    head: str,
    base: str,
    title: str,
    body: str,
) -> str:
    """Create a pull request or return the existing open one."""
    if _is_forgejo(config):
        return forgejo.create_pr(
            config.repo.url,
            config.repo.full_name,
            token,
            head=head,
            base=base,
            title=title,
            body=body,
        )
    return github.create_pr(
        config.repo.full_name,
        token,
        head=head,
        base=base,
        title=title,
        body=body,
    )


def get_pr_status(config: Config, pr_url: str, token: str) -> PullRequestStatus:
    """Return the pull-request state and normalized checks."""
    if _is_forgejo(config):
        return forgejo.get_pr_status(
            config.repo.url,
            config.repo.full_name,
            pr_url,
            token,
        )
    return github.get_pr_status(config.repo.full_name, pr_url, token)


def merge_pr(config: Config, pr_url: str, token: str) -> str:
    """Squash-merge a pull request and return its merge commit, if reported."""
    if _is_forgejo(config):
        return forgejo.merge_pr(
            config.repo.url,
            config.repo.full_name,
            pr_url,
            token,
        )
    return github.merge_pr(config.repo.full_name, pr_url, token)


def delete_branch(config: Config, branch: str, token: str) -> None:
    """Delete a stale remote branch, ignoring an already-missing ref."""
    if _is_forgejo(config):
        forgejo.delete_branch(
            config.repo.url,
            config.repo.full_name,
            branch,
            token,
        )
    else:
        github.delete_branch(config.repo.full_name, branch, token)
